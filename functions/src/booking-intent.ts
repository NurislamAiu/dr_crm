/**
 * «Хочет записаться» — метка для входящих, где клиент явно спрашивает про
 * запись/приём. Менеджеры отвечают не всем одинаково быстро, а такие
 * обращения — самые горячие: человек уже готов записаться, просто ждёт
 * ответа. В списке чатов такие обращения помечаются отдельно, чтобы
 * не потерялись среди обычной переписки.
 *
 * Сервер только определяет факт по тексту сообщения; момент записывается в
 * conv.wantsAppointmentAt (см. вызовы detectBookingIntent). Бейдж временный:
 * клиентское FsConversation.wantsAppointment гаснет через 24 часа после
 * последнего такого сообщения — старое обращение не маячит в списке вечно.
 * Как только человек стал лидом/VIP/записан на массаж, список чатов и так
 * покажет его бейджем ЛИД/VIP (приоритет на клиенте отдаётся сохранённому
 * статусу, а не этому флагу).
 */
import { normalizeTopicText } from "./topics";

/// Корень покрывает «записаться», «запишите», «запись», «записываться»…
const ROOT = "запис";

const PHRASES = [
  "хочу на прием",
  "хочу на приём",
  "нужна запись",
  "есть запись",
  "когда можно прийти",
  "можно прийти",
  "можно к вам",
  "как попасть на прием",
  "как попасть на приём",
  "свободное время есть",
  "какие есть свободные",
  "когда свободно",
  "когда есть время",
].map(normalizeTopicText);

export function detectBookingIntent(text: string): boolean {
  const t = normalizeTopicText(text);
  if (t.length < 3) return false;
  if (t.includes(ROOT)) return true;
  return PHRASES.some((p) => t.includes(p));
}
