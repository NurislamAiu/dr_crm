import 'package:audio_session/audio_session.dart';

/// Перевести аудио-сессию телефона в режим ВОСПРОИЗВЕДЕНИЯ.
///
/// Лечит «плеер играет, а звука нет». После записи голосового (пакет record)
/// сессия iPhone остаётся в режиме запись+разговор — звук уходит в тихий
/// разговорный динамик у уха, и голосовые «немые». Категория playback
/// возвращает громкий динамик и играет даже при выключенном звонке
/// (беззвучный переключатель iPhone плеер игнорирует — как в WhatsApp).
/// На Android заодно корректно берётся аудио-фокус.
///
/// Вызывается перед каждым воспроизведением: повторный вызов дешёвый, а
/// сессию к этому моменту мог перенастроить кто угодно.
Future<void> ensurePlaybackSession() async {
  try {
    final session = await AudioSession.instance;
    await session.configure(const AudioSessionConfiguration.music());
  } catch (_) {
    // Не удалось настроить — пробуем играть как есть.
  }
}
